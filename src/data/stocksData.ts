// Helper to generate realistic historical price curve
function generateHistory(basePrice: number, volatility: number) {
  const generatePoints = (count: number, intervalDays: number, trend: number) => {
    const points = [];
    let current = basePrice * (1 - (trend * (count / 100)));
    const now = new Date();
    
    for (let i = count - 1; i >= 0; i--) {
      const d = new Date(now.getTime() - (i * intervalDays * 24 * 60 * 60 * 1000));
      const delta = (Math.random() - 0.48) * (basePrice * volatility);
      current = Math.max(basePrice * 0.4, Number((current + delta).toFixed(2)));
      
      // on the last day, snap to basePrice
      if (i === 0) current = basePrice;
      
      const dateStr = intervalDays <= 1 
        ? d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
        : d.toLocaleDateString('en-GB', { month: 'short', day: 'numeric' });
        
      points.push({
        date: dateStr,
        price: Number(current.toFixed(2)),
        volume: Math.floor(Math.random() * 50000 + 5000)
      });
    }
    return points;
  };

  return {
    '1D': [
      { date: '10:00', price: Number((basePrice * 0.995).toFixed(2)), volume: 12000 },
      { date: '11:00', price: Number((basePrice * 0.998).toFixed(2)), volume: 24500 },
      { date: '12:00', price: Number((basePrice * 1.002).toFixed(2)), volume: 38900 },
      { date: '13:00', price: Number((basePrice * 1.000).toFixed(2)), volume: 15400 },
      { date: '14:00', price: Number((basePrice * 1.005).toFixed(2)), volume: 42000 },
      { date: '15:00', price: basePrice, volume: 55000 }
    ],
    '1W': generatePoints(7, 1, 0.015),
    '1M': generatePoints(30, 1, 0.04),
    '3M': generatePoints(60, 1.5, 0.08),
    '1Y': generatePoints(12, 30, 0.18),
    'ALL': generatePoints(24, 60, 0.35)
  };
}

